# Style
# -----------------------------

def setup_style():
    sns.set_theme(
        context="paper",
        style="whitegrid",
        font="DejaVu Sans",
        rc={
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.labelsize": 9,
            "axes.titlesize": 9,
            "xtick.labelsize": 8,
            "ytick.labelsize": 8,
            "legend.fontsize": 8,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "figure.dpi": 160,
            "savefig.dpi": 300,
            "savefig.bbox": "tight",
            "savefig.pad_inches": 0.02,
        },
    )


BACKEND_PALETTE = {
    "triton": "#0072B2",
    "cutile": "#D55E00",
    "unknown": "#999999",
}

DIAGNOSIS_ORDER = [
    "BANK_CONFLICT_CONFIRMED_SEVERE",
    "BANK_CONFLICT_CONFIRMED_MODERATE",
    "BANK_CONFLICT_CONFIRMED_MILD",
    "BANK_CONFLICT_LIKELY",
    "DIVERGENCE_CONFOUNDED",
    "DIVERGENCE_CONFOUNDED_NO_CONFLICT",
    "NO_BANK_CONFLICT_EVIDENCE",
    "NO_SHARED_MEMORY_EVIDENCE",
    "INSUFFICIENT_METRICS",
]


# -----------------------------
# Metadata parsing
# -----------------------------

DTYPE_PATTERNS = [
    "fp8_e4m3fn",
    "fp8_e5m2",
    "fp16",
    "fp32",
    "bf16",
    "int8",
    "int32",
]


def parse_backend_dtype_from_file(file_name: str) -> tuple[str, str]:
    """
    Parse backend and dtype from analyzer's file field.

    Expected examples:
      matmul_fp32_fp16_fp8__triton_fp32.raw.csv
      matmul_fp32_fp16_fp8__cutile_fp8_e5m2.raw.csv
      streamk_matmul__triton_fp16.raw.csv

    Returns:
      backend, dtype
    """
    text = str(file_name)

    backend = "unknown"
    if "__triton_" in text or re.search(r"(^|__)triton_", text):
        backend = "triton"
    elif "__cutile_" in text or re.search(r"(^|__)cutile_", text):
        backend = "cutile"

    dtype = "unknown"
    for d in DTYPE_PATTERNS:
        if re.search(rf"(^|_|__){re.escape(d)}($|_|\.|raw|csv)", text):
            dtype = d
            # Need to avoid picking fp32 from operator name matmul_fp32_fp16_fp8
            # if backend stem has a more specific dtype. Prefer substring after backend.
            if backend in {"triton", "cutile"}:
                m = re.search(rf"{backend}_(.+?)\.raw\.csv", text)
                if m:
                    tail = m.group(1)
                    for dd in DTYPE_PATTERNS:
                        if dd in tail:
                            dtype = dd
                            break
            break

    return backend, dtype


def parse_operator_from_file(row: pd.Series) -> str:
    """
    Prefer analyzer's operator column, but repair cases where it includes
    filename-derived suffixes.
    """
    op = str(row.get("operator", "unknown"))
    file_name = str(row.get("file", ""))

    # If file is like op__stem.raw.csv, use prefix.
    if "__" in file_name:
        return file_name.split("__", 1)[0]

    return op


def enrich(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()

    df["operator_clean"] = df.apply(parse_operator_from_file, axis=1)

    parsed = df["file"].apply(parse_backend_dtype_from_file)
    df["backend_from_file"] = [x[0] for x in parsed]
    df["dtype_from_file"] = [x[1] for x in parsed]

    # Prefer parsed backend/dtype because initial analyzer's heuristic may be weak.
    df["backend"] = df["backend_from_file"]
    df["dtype_clean"] = df["dtype_from_file"]

    # If mode is unknown, leave it; many NCU folders may not encode default/autotune.
    if "mode" not in df.columns:
        df["mode"] = "unknown"

    # Numeric cleanup.
    numeric_cols = [
        "bank_conflicts",
        "shared_wavefronts",
        "conflict_per_wavefront",
        "branch_efficiency_pct",
        "ipc_gap_ratio",
        "executed_ipc_active",
        "issued_ipc_active",
        "shared_utilization_pct",
        "sm_busy_pct",
        "dram_busy_pct",
        "stall_mio_throttle_pct",
        "stall_long_scoreboard_pct",
        "stall_barrier_pct",
    ]
    for c in numeric_cols:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce")

    # More interpretable percent-like conflict score.
    df["conflict_per_wavefront_pct"] = 100.0 * df["conflict_per_wavefront"]

    # Short labels.
    df["case_label"] = df["operator_clean"] + "/" + df["backend"] + "/" + df["dtype_clean"]

    return df


