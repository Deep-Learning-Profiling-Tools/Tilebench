#!/usr/bin/env python3
"""
Make paper-ready figures from ncu_bank_conflict_summary.csv.

This script assumes the summary was generated by analyze_ncu_bank_conflicts.py.

It enriches metadata from filenames such as:
  matmul_fp32_fp16_fp8__triton_fp32.raw.csv
  matmul_fp32_fp16_fp8__cutile_fp8_e5m2.raw.csv

Outputs:
  - PDF/PNG figures
  - enriched summary CSV
  - LaTeX table of top bank-conflict cases
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import numpy as np
import pandas as pd

import matplotlib as mpl
import matplotlib.pyplot as plt
import seaborn as sns


