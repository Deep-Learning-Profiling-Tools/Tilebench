# Figures
# -----------------------------

def plot_heatmap_backend_dtype(df: pd.DataFrame, out_dir: Path):
    """
    Heatmap rows: operator/backend
    columns: dtype
    values: median bank conflicts per shared wavefront.
    """
    d = df.copy()
    d = d[np.isfinite(d["conflict_per_wavefront"])]

    if d.empty:
        print("[WARN] No finite conflict_per_wavefront values for heatmap.")
        return

    d["row_label"] = d["operator_clean"] + " / " + d["backend"]

    pivot = d.pivot_table(
        index="row_label",
        columns="dtype_clean",
        values="conflict_per_wavefront_pct",
        aggfunc="median",
    )

    # Sort by max conflict.
    pivot["__max__"] = pivot.max(axis=1)
    pivot = pivot.sort_values("__max__", ascending=False).drop(columns="__max__")

    dtype_order = [x for x in DTYPE_PATTERNS if x in pivot.columns]
    other_cols = [x for x in pivot.columns if x not in dtype_order]
    pivot = pivot[dtype_order + other_cols]

    fig_h = max(3.0, 0.23 * len(pivot) + 0.6)
    fig_w = max(4.2, 0.7 * len(pivot.columns) + 2.0)
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))

    sns.heatmap(
        pivot,
        ax=ax,
        cmap="magma_r",
        linewidths=0.35,
        linecolor="white",
        cbar_kws={"label": "bank conflicts / shared wavefront (%)"},
    )

    ax.set_title("Shared-memory bank-conflict severity across NCU reports")
    ax.set_xlabel("dtype")
    ax.set_ylabel("operator / backend")

    savefig(fig, out_dir, "fig_ncu_conflict_heatmap_backend_dtype")


def plot_backend_comparison(df: pd.DataFrame, out_dir: Path):
    """
    Paired scatter: Triton conflict score vs cuTile conflict score for same operator/dtype.
    """
    d = df.copy()
    d = d[np.isfinite(d["conflict_per_wavefront_pct"])]
    d = d[d["backend"].isin(["triton", "cutile"])]

    if d.empty:
        return

    pivot = d.pivot_table(
        index=["operator_clean", "dtype_clean"],
        columns="backend",
        values="conflict_per_wavefront_pct",
        aggfunc="median",
    ).reset_index()

    if not {"triton", "cutile"}.issubset(pivot.columns):
        print("[WARN] Cannot make backend comparison; missing triton or cutile.")
        return

    pivot = pivot[np.isfinite(pivot["triton"]) & np.isfinite(pivot["cutile"])]

    if pivot.empty:
        print("[WARN] No paired Triton/cuTile rows for backend comparison.")
        return

    fig, ax = plt.subplots(figsize=(3.4, 3.1))

    sns.scatterplot(
        data=pivot,
        x="triton",
        y="cutile",
        hue="dtype_clean",
        s=42,
        alpha=0.85,
        ax=ax,
    )

    lo = max(1e-4, min(pivot["triton"].min(), pivot["cutile"].min()) * 0.5)
    hi = max(pivot["triton"].max(), pivot["cutile"].max()) * 2.0
    ax.plot([lo, hi], [lo, hi], color="black", linestyle="--", linewidth=1.0)

    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("Triton conflicts / shared wavefront (%)")
    ax.set_ylabel("cuTile conflicts / shared wavefront (%)")
    ax.set_title("Backend comparison of bank-conflict severity")
    ax.legend(frameon=False, title="dtype", loc="best")
    ax.grid(True, which="both", linewidth=0.35, alpha=0.45)

    savefig(fig, out_dir, "fig_ncu_conflict_backend_comparison")


def plot_branch_confounder(df: pd.DataFrame, out_dir: Path):
    d = df.copy()
    d = d[np.isfinite(d["conflict_per_wavefront_pct"])]

    if d.empty:
        return

    fig, ax = plt.subplots(figsize=(4.0, 2.8))

    sns.scatterplot(
        data=d,
        x="branch_efficiency_pct",
        y="conflict_per_wavefront_pct",
        hue="backend",
        style="diagnosis",
        palette=BACKEND_PALETTE,
        s=45,
        alpha=0.85,
        ax=ax,
    )

    ax.axvline(99.0, color="black", linestyle="--", linewidth=0.9)
    ax.axvline(95.0, color="gray", linestyle=":", linewidth=0.9)

    ax.set_yscale("log")
    ax.set_xlabel("Branch efficiency (%)")
    ax.set_ylabel("Bank conflicts / shared wavefront (%)")
    ax.set_title("Branch divergence as a confounder")
    ax.legend(frameon=False, fontsize=6, loc="best")
    ax.grid(True, which="both", linewidth=0.35, alpha=0.45)

    savefig(fig, out_dir, "fig_ncu_branch_confounder")


def plot_diagnosis_counts(df: pd.DataFrame, out_dir: Path):
    d = df.copy()

    order = [x for x in DIAGNOSIS_ORDER if x in set(d["diagnosis"])]
    rest = [x for x in d["diagnosis"].dropna().unique() if x not in order]
    order = order + sorted(rest)

    fig_h = max(2.5, 0.28 * len(order) + 0.8)
    fig, ax = plt.subplots(figsize=(5.0, fig_h))

    sns.countplot(
        data=d,
        y="diagnosis",
        order=order,
        hue="backend",
        palette=BACKEND_PALETTE,
        ax=ax,
    )

    ax.set_xlabel("# NCU reports")
    ax.set_ylabel("")
    ax.set_title("Automated NCU diagnosis categories")
    ax.legend(frameon=False, title="backend", loc="lower right")

    savefig(fig, out_dir, "fig_ncu_diagnosis_counts")


def plot_top_conflict_cases(df: pd.DataFrame, out_dir: Path, top_k: int = 20):
    d = df.copy()
    d = d[np.isfinite(d["conflict_per_wavefront_pct"])]
    d = d.sort_values("conflict_per_wavefront_pct", ascending=False).head(top_k)
    d = d.sort_values("conflict_per_wavefront_pct", ascending=True)

    if d.empty:
        return

    fig_h = max(3.0, 0.25 * len(d) + 0.5)
    fig, ax = plt.subplots(figsize=(6.6, fig_h))

    colors = d["backend"].map(BACKEND_PALETTE).fillna("#999999")

    ax.barh(
        np.arange(len(d)),
        d["conflict_per_wavefront_pct"],
        color=colors,
        alpha=0.9,
    )

    ax.set_yticks(np.arange(len(d)))
    ax.set_yticklabels(d["case_label"])
    ax.set_xscale("log")
    ax.set_xlabel("Bank conflicts / shared wavefront (%)")
    ax.set_title(f"Top {top_k} bank-conflict cases")
    ax.grid(True, axis="x", which="both", linewidth=0.35, alpha=0.45)

    # Legend.
    handles = [
        mpl.patches.Patch(color=v, label=k)
        for k, v in BACKEND_PALETTE.items()
        if k in set(d["backend"])
    ]
    ax.legend(handles=handles, frameon=False, loc="lower right")

    savefig(fig, out_dir, "fig_ncu_top_conflict_cases")


def plot_stall_relation(df: pd.DataFrame, out_dir: Path):
    """
    Optional diagnostic plot:
    conflict score vs MIO throttle / long scoreboard.
    """
    metrics = [
        ("stall_mio_throttle_pct", "MIO throttle stall (%)", "fig_ncu_conflict_vs_mio_throttle"),
        ("stall_long_scoreboard_pct", "Long scoreboard stall (%)", "fig_ncu_conflict_vs_long_scoreboard"),
    ]

    for col, xlabel, fname in metrics:
        if col not in df.columns:
            continue

        d = df[np.isfinite(df["conflict_per_wavefront_pct"]) & np.isfinite(df[col])].copy()
        if d.empty:
            continue

        fig, ax = plt.subplots(figsize=(3.4, 2.7))
        sns.scatterplot(
            data=d,
            x=col,
            y="conflict_per_wavefront_pct",
            hue="backend",
            palette=BACKEND_PALETTE,
            s=42,
            alpha=0.85,
            ax=ax,
        )
        ax.set_yscale("log")
        ax.set_xlabel(xlabel)
        ax.set_ylabel("Bank conflicts / shared wavefront (%)")
        ax.set_title("Conflict severity vs stall signal")
        ax.legend(frameon=False, title="")
        ax.grid(True, which="both", linewidth=0.35, alpha=0.45)
        savefig(fig, out_dir, fname)


def write_top_cases_table(df: pd.DataFrame, out_dir: Path, top_k: int = 12):
    d = df.copy()
    d = d[np.isfinite(d["conflict_per_wavefront_pct"])]
    d = d.sort_values("conflict_per_wavefront_pct", ascending=False).head(top_k)

    cols = [
        "operator_clean",
        "backend",
        "dtype_clean",
        "diagnosis",
        "bank_conflicts",
        "shared_wavefronts",
        "conflict_per_wavefront_pct",
        "branch_efficiency_pct",
        "ipc_gap_ratio",
    ]

    keep = [c for c in cols if c in d.columns]
    t = d[keep].copy()

    rename = {
        "operator_clean": "Operator",
        "backend": "Backend",
        "dtype_clean": "Dtype",
        "diagnosis": "Diagnosis",
        "bank_conflicts": "Bank conflicts",
        "shared_wavefronts": "Shared wavefronts",
        "conflict_per_wavefront_pct": "Conflicts / wavefront (\\%)",
        "branch_efficiency_pct": "Branch eff. (\\%)",
        "ipc_gap_ratio": "IPC gap",
    }
    t = t.rename(columns=rename)

    for c in t.columns:
        if c in {"Bank conflicts", "Shared wavefronts"}:
            t[c] = t[c].map(lambda x: f"{x:.3g}" if pd.notna(x) else "")
        elif c in {"Conflicts / wavefront (\\%)", "Branch eff. (\\%)"}:
            t[c] = t[c].map(lambda x: f"{x:.2f}" if pd.notna(x) else "")
        elif c == "IPC gap":
            t[c] = t[c].map(lambda x: f"{x:.3f}" if pd.notna(x) else "")

    latex = t.to_latex(
        index=False,
        escape=False,
        caption="Top NCU reports by normalized shared-memory bank-conflict severity.",
        label="tab:ncu_bank_conflict_top_cases",
    )

    (out_dir / "table_ncu_bank_conflict_top_cases.tex").write_text(latex)


# -----------------------------
# Main
# -----------------------------

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--summary-csv", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--top-k", type=int, default=20)
    args = parser.parse_args()

    setup_style()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    df = pd.read_csv(args.summary_csv)
    df = enrich(df)

    enriched_path = args.out_dir.parent / "ncu_bank_conflict_summary_enriched.csv"
    df.to_csv(enriched_path, index=False)

    plot_heatmap_backend_dtype(df, args.out_dir)
    plot_backend_comparison(df, args.out_dir)
    plot_branch_confounder(df, args.out_dir)
    plot_diagnosis_counts(df, args.out_dir)
    plot_top_conflict_cases(df, args.out_dir, top_k=args.top_k)
    plot_stall_relation(df, args.out_dir)
    write_top_cases_table(df, args.out_dir, top_k=min(12, args.top_k))

    print(f"Wrote enriched summary: {enriched_path}")
    print(f"Wrote figures to: {args.out_dir}")


if __name__ == "__main__":
    main()