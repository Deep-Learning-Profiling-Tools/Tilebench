"""NKI histogramming: per-bin count via a chunked reduction over the input.

Two Python loops walk the (bin_block x chunk) grid: bins are split into
``num_bin_blocks = ceil(num_bins/128)`` static blocks (``nl.dynamic_range``
cannot nest, so this outer loop stays a plain Python ``range`` -- it tops out
at 32 in the current sweep, cheap to unroll on its own). Each bin block's
``num_chunks = ceil(N/8192)`` chunks used to be a second unrolled Python loop,
giving ``num_bin_blocks * num_chunks`` copies of the loop body and blowing the
compiler's instruction budget at the sweep's largest case (32 bin blocks x
8,192 chunks = 262,144 unrolled iterations -> ``[NCC_EBVF030] Instructions
generated by compiler 35,913,891 exceeds the typical limit of 5,000,000``).

Fixed the same way as 1d_conv/3d_conv/block_sparse_attention: the full
(non-tail) chunks of each bin block now run inside a single ``nl.dynamic_range``
on-device loop, so the emitted instruction count no longer multiplies by
``num_chunks`` -- it's flat in ``bi`` alone. The (at most one) trailing partial
chunk, when ``N`` isn't a multiple of 8192, is peeled out and handled
statically with an exactly-sized load, so every dynamic iteration is uniform
(no runtime masking needed -- ``N`` is a compile-time constant per trace, so
the tail's exact size is already known when tracing).

``nl.dynamic_range`` only exists in the standalone ``nki`` package (used by
1d_conv/3d_conv/block_sparse_attention/flash_attention/radix_sort), not in the
``neuronxcc.nki`` package the rest of this repo's simpler elementwise kernels
import -- the two are different API generations, and only the former has
on-device loop support. Moving to it drops the numpy-like ``nl.load``/
``nl.store``/``nl.broadcast_to`` sugar the original version used, in favor of
explicit ``nisa`` primitives and access patterns:

* A ``nl.dynamic_range`` index is a hardware register that supports no
  arithmetic and cannot be folded into a static slice. The chunk's read
  offset is therefore kept in a 1x1 int32 SBUF scalar, advanced with
  ``nisa.tensor_scalar`` each iteration, and applied to the HBM load via
  ``.ap(scalar_offset=..., indirect_dim=1)``.
* Comparing every chunk value against a whole bin block's ids needs the
  chunk (loaded 1-partition-wide) broadcast to ``bin_size`` partitions.
  ``.ap()``'s partition stride can't express a cross-partition broadcast (only
  free-axis broadcast via a zero stride is legal); this kernel instead
  broadcasts with the standard systolic-array trick, an ``nc_matmul`` against
  an all-ones stationary operand, tiled to the PSUM bank's 512-fp32-element
  free-dim limit.
* On-device control flow only lowers correctly when the kernel's launch
  degree matches the LNC the XLA module is compiled for, hence
  ``histogram_kernel[_lnc_degree()]`` in ``run()``.
"""
import torch

from core.nki_timer import lnc_degree as _lnc_degree

try:
    import nki
    import nki.language as nl
    import nki.isa as nisa
    PMAX = nl.tile_size.pmax
except ImportError:
    nki = None
    PMAX = 128

# PSUM bank free size in fp32 elements on trn2 (NeuronCore-v3): also the
# maximum free size of an nc_matmul moving/output operand.
PSUM_FMAX = 512

# Fewer full chunks than this and an on-device loop is not worth its overhead,
# so the chunks are unrolled at compile time instead.
MIN_DYNAMIC_CHUNKS = 2


def div_ceil(numerator: int, denominator: int) -> int:
    return (numerator + denominator - 1) // denominator


if nki is not None:
    def _accumulate_chunk(count, bin_iota, bin_size, ones, values, size,
                          free_offset=0, free_off_sb=None):
        """Add one chunk's (``size`` values, always an exact in-range read)
        per-bin match counts into ``count``.

        On the dynamic path (``free_off_sb`` given) the caller's on-device loop
        guarantees the chunk lies fully inside ``values``, and the read offset
        lives in an SBUF scalar the loop advances -- a ``dynamic_range``
        register supports no arithmetic, so it cannot be folded into a static
        slice and is instead applied via ``.ap(scalar_offset=...,
        indirect_dim=1)``. On the static path ``free_offset`` is a plain
        Python int and the load is a normal compile-time slice.
        """
        v_i32 = nl.ndarray((1, size), dtype=nl.int32, buffer=nl.sbuf)
        if free_off_sb is not None:
            N = values.shape[1]
            nisa.dma_copy(
                dst=v_i32,
                src=values.ap(pattern=[[N, 1], [1, size]], offset=0,
                              scalar_offset=free_off_sb, indirect_dim=1),
            )
        else:
            nisa.dma_copy(dst=v_i32, src=values[0:1, free_offset:free_offset + size])

        v_f32 = nl.ndarray((1, size), dtype=nl.float32, buffer=nl.sbuf)
        nisa.tensor_copy(dst=v_f32, src=v_i32)

        # Broadcast the single-partition chunk to `bin_size` partitions so it
        # can be compared against every bin id in the block at once: `.ap()`
        # only supports free-axis broadcast (zero stride), not cross-partition,
        # so this uses an nc_matmul against an all-ones stationary operand
        # instead (`ones^T @ v_f32` replicates the row into every output
        # partition), tiled to PSUM's free-dim limit.
        v_bcast = nl.ndarray((bin_size, size), dtype=nl.int32, buffer=nl.sbuf)
        for t in range(div_ceil(size, PSUM_FMAX)):
            off = t * PSUM_FMAX
            w = min(PSUM_FMAX, size - off)
            v_psum = nl.ndarray((bin_size, w), dtype=nl.float32, buffer=nl.psum)
            nisa.nc_matmul(dst=v_psum, stationary=ones, moving=v_f32[0:1, off:off + w])
            nisa.tensor_copy(dst=v_bcast[0:bin_size, off:off + w], src=v_psum)

        eq = nl.ndarray((bin_size, size), dtype=nl.int32, buffer=nl.sbuf)
        nisa.tensor_tensor(dst=eq, data1=bin_iota.ap(pattern=[[1, bin_size], [0, size]]),
                           data2=v_bcast, op=nl.equal)
        chunk_sum = nl.ndarray((bin_size, 1), dtype=nl.int32, buffer=nl.sbuf)
        nisa.tensor_reduce(dst=chunk_sum, data=eq, op=nl.add, axis=(1,))
        nisa.tensor_tensor(dst=count, data1=count, data2=chunk_sum, op=nl.add)

    @nki.jit
    def histogram_kernel(values, num_bins):
        N = values.shape[1]
        chunk_size = 8192
        num_bin_blocks = div_ceil(num_bins, PMAX)
        num_full_chunks = N // chunk_size
        tail_size = N - num_full_chunks * chunk_size

        hbm_result = nl.ndarray((num_bins, 1), dtype=nl.int32, buffer=nl.shared_hbm)

        for bi in range(num_bin_blocks):
            bin_offset = bi * PMAX
            bin_size = min(PMAX, num_bins - bin_offset)

            bin_iota = nl.ndarray((bin_size, 1), dtype=nl.int32, buffer=nl.sbuf)
            nisa.iota(dst=bin_iota, pattern=[[0, 1]], offset=bin_offset,
                     channel_multiplier=1)

            ones = nl.ndarray((1, bin_size), dtype=nl.float32, buffer=nl.sbuf)
            nisa.memset(dst=ones, value=1.0)

            count = nl.ndarray((bin_size, 1), dtype=nl.int32, buffer=nl.sbuf)
            nisa.memset(dst=count, value=0)

            if num_full_chunks >= MIN_DYNAMIC_CHUNKS:
                free_off_sb = nl.ndarray((1, 1), dtype=nl.int32, buffer=nl.sbuf)
                nisa.memset(dst=free_off_sb, value=0)
                for _ in nl.dynamic_range(num_full_chunks):
                    _accumulate_chunk(count, bin_iota, bin_size, ones, values,
                                      chunk_size, free_off_sb=free_off_sb)
                    nisa.tensor_scalar(dst=free_off_sb, data=free_off_sb,
                                       op0=nl.add, operand0=chunk_size)
            else:
                for ci in range(num_full_chunks):
                    _accumulate_chunk(count, bin_iota, bin_size, ones, values,
                                      chunk_size, free_offset=ci * chunk_size)

            if tail_size > 0:
                _accumulate_chunk(count, bin_iota, bin_size, ones, values, tail_size,
                                  free_offset=num_full_chunks * chunk_size)

            nisa.dma_copy(dst=hbm_result[bin_offset:bin_offset + bin_size, 0:1],
                         src=count)

        return hbm_result


def run(input: torch.Tensor, N: int, num_bins: int, block_size: int = 1024,
        autotune: bool = False, lnc_degree: int | None = None, **kwargs) -> torch.Tensor:
    values_2d = input.reshape(1, -1).to(torch.int32)
    degree = lnc_degree if lnc_degree is not None else _lnc_degree()
    hist = histogram_kernel[degree](values_2d, num_bins)
    return hist.reshape(-1)


def get_last_config() -> dict | None:
    return None
